def key_path(paths, device_id: str) -> Path:
    return paths["keys"] / f"{device_id}.key"


def csr_path(paths, device_id: str) -> Path:
    return paths["csr"] / f"{device_id}.csr"


def load_csr(path: Path) -> x509.CertificateSigningRequest:
    return x509.load_pem_x509_csr(path.read_bytes())


def load_key(path: Path):
    return serialization.load_pem_private_key(path.read_bytes(), password=None)


def public_der(public_key) -> bytes:
    return public_key.public_bytes(
        serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo
    )


def write_existing_key(path: Path, key=None) -> bytes:
    """Write a test-generated P-256 key at path (mode 0600). Returns its bytes."""
    key = key or ec.generate_private_key(ec.SECP256R1())
    pem = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(pem)
    path.chmod(0o600)
    return pem


# ---- no key: create key and CSR ----


def test_missing_key_creates_ec_p256_key(run, paths, two_devices):
    code, _, _ = run()

    assert code == 0
    for device_id in two_devices:
        key = load_key(key_path(paths, device_id))
        assert isinstance(key, ec.EllipticCurvePrivateKey)
        assert isinstance(key.curve, ec.SECP256R1)


def test_new_key_file_has_mode_0600(run, paths, two_devices):
    run()

    for device_id in two_devices:
        mode = stat.S_IMODE(key_path(paths, device_id).stat().st_mode)
        assert mode == 0o600


def test_new_key_is_unencrypted_pkcs8_pem(run, paths, two_devices):
    run()

    text = key_path(paths, WEARABLE).read_text(encoding="ascii")
    assert text.startswith("-----BEGIN " + PRIVATE_KEY_TEXT + "-----")


def test_missing_key_creates_csr_with_cn_device_id(run, paths, two_devices):
    run()

    for device_id in two_devices:
        csr = load_csr(csr_path(paths, device_id))
        cns = csr.subject.get_attributes_for_oid(NameOID.COMMON_NAME)
        assert [a.value for a in cns] == [device_id]
        # Subject is exactly CN=<id>, nothing else.
        assert len(list(csr.subject)) == 1


def test_csr_is_signed_by_and_matches_the_new_key(run, paths, two_devices):
    run()

    for device_id in two_devices:
        csr = load_csr(csr_path(paths, device_id))
        key = load_key(key_path(paths, device_id))
        assert csr.is_signature_valid
        assert public_der(csr.public_key()) == public_der(key.public_key())


def test_missing_key_output_says_created(run, paths, two_devices):
    _, out, _ = run()

