# ---- output never contains key material (criterion 14) ----


def test_output_never_contains_private_key_text(run, paths, two_devices):
    outputs = []
    # Fresh create.
    outputs.append(run())
    # Key exists, CSR missing.
    csr_path(paths, WEARABLE).unlink()
    outputs.append(run())
    # Both exist.
    outputs.append(run())
    # Single device.
    outputs.append(run("--device", BEDROOM))

    key_bodies = [
        line
        for d in two_devices
        for line in key_path(paths, d).read_text(encoding="ascii").splitlines()
        if not line.startswith("-----")
    ]
    for code, out, err in outputs:
        assert code == 0
        assert PRIVATE_KEY_TEXT not in out + err
        assert "-----BEGIN" not in out + err
        for body_line in key_bodies:
            assert body_line not in out + err


def test_error_output_never_contains_private_key_text(run, paths, two_devices):
    # A key file that parses as PEM but is the wrong algorithm triggers an error path.
    write_existing_key(
        key_path(paths, WEARABLE),
        rsa.generate_private_key(public_exponent=65537, key_size=2048),
    )

    _, out, err = run()

    assert PRIVATE_KEY_TEXT not in out + err
    assert "-----BEGIN" not in out + err


def test_validation_error_output_has_no_file_contents(run, paths):
    # A devices.json that holds a key-like string must not be echoed back.
    secret = "synthetic-" + PRIVATE_KEY_TEXT.replace(" ", "-")
    paths["devices"].write_text(
        json.dumps({"devices": [{"id": WEARABLE, "type": secret, "canary": False}]}),
        encoding="utf-8",
    )

    _, out, err = run()

    assert secret not in out + err
