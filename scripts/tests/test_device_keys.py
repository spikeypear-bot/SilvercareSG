# ---- key but no CSR: recreate CSR from the existing key ----


def test_existing_key_without_csr_recreates_csr_from_that_key(run, paths, two_devices):
    existing = ec.generate_private_key(ec.SECP256R1())
    write_existing_key(key_path(paths, WEARABLE), existing)

    code, out, _ = run()

    assert code == 0
    csr = load_csr(csr_path(paths, WEARABLE))
    assert csr.is_signature_valid
    assert public_der(csr.public_key()) == public_der(existing.public_key())
    cns = csr.subject.get_attributes_for_oid(NameOID.COMMON_NAME)
    assert [a.value for a in cns] == [WEARABLE]
    assert f"{WEARABLE}: key exists, created CSR" in out


def test_existing_key_without_csr_is_not_modified(run, paths, two_devices):
    path = key_path(paths, WEARABLE)
    before = write_existing_key(path)
    mtime_before = path.stat().st_mtime_ns

    run()

    assert path.read_bytes() == before
    assert path.stat().st_mtime_ns == mtime_before


