# ---- never overwrite a key ----


def test_write_new_key_refuses_to_overwrite_existing_file(device_keys, tmp_path):
    path = tmp_path / f"{WEARABLE}.key"
    path.write_bytes(b"synthetic placeholder")

    with pytest.raises(FileExistsError):
        device_keys.write_new_key(path)

    assert path.read_bytes() == b"synthetic placeholder"


def test_unreadable_existing_key_fails_without_overwriting_it(run, paths, two_devices):
    path = key_path(paths, WEARABLE)
    path.parent.mkdir(parents=True)
    path.write_bytes(b"synthetic-not-a-key-marker")
    path.chmod(0o600)

    code, out, err = run()

    assert code != 0
    assert path.read_bytes() == b"synthetic-not-a-key-marker"
    assert not csr_path(paths, WEARABLE).exists()
    assert WEARABLE in err
    assert "synthetic-not-a-key-marker" not in out + err
    # The other device is still handled.
    assert key_path(paths, BEDROOM).exists()


def test_existing_non_p256_key_fails_without_overwriting_it(run, paths, two_devices):
    path = key_path(paths, WEARABLE)
    before = write_existing_key(
        path, rsa.generate_private_key(public_exponent=65537, key_size=2048)
    )

    code, _, err = run()

    assert code != 0
    assert path.read_bytes() == before
    assert not csr_path(paths, WEARABLE).exists()
    assert "P-256" in err


